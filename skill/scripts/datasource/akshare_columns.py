def apply() -> int:
    """把 AkShare 列名注入 schema 的 FieldSpec。返回修改的字段数。"""
    from . import schema

    n = 0
    for ds_name, mapping in AKSHARE_COLUMNS.items():
        ds = schema.DATASETS.get(ds_name)
        if ds is None:
            continue
        for f in ds.fields:
            col = mapping.get(f.key)
            if col and not f.akshare:
                object.__setattr__(f, "akshare", col)
                n += 1
    return n
